const DICTS: Record<Lang, Dict> = { en, ur, roman_ur };

export function isRTL(lang: Lang): boolean {
  return lang === 'ur';
}

const UR_DIGITS = ['۰', '۱', '۲', '۳', '۴', '۵', '۶', '۷', '۸', '۹'];
// Localize Western digits to Urdu (Eastern Arabic) numerals when the language is Urdu.
export function localizeNum(value: string | number, lang: Lang): string {
  const s = String(value ?? '');
  return lang === 'ur' ? s.replace(/[0-9]/g, (d) => UR_DIGITS[Number(d)]) : s;
}

export function makeT(lang: Lang) {
  const dict = DICTS[lang] || en;
  return (key: string, vars?: Record<string, string | number>): string => {
    let s = dict[key] ?? en[key] ?? key;
    if (vars) for (const k of Object.keys(vars)) s = s.replace(`{${k}}`, String(vars[k]));
    return s;
  };
}

